  function apply(lang) {
    document.documentElement.lang = lang === "kk" ? "kk" : "ru";
    var dict = DICT[lang] || DICT.ru;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var val = dict[el.getAttribute("data-i18n")];
      if (val === undefined) return;
      if (el.namespaceURI === "http://www.w3.org/2000/svg") {
        el.textContent = val;
      } else {
        el.innerHTML = val;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var val = dict[el.getAttribute("data-i18n-placeholder")];
      if (val !== undefined) el.setAttribute("placeholder", val);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var val = dict[el.getAttribute("data-i18n-aria")];
      if (val !== undefined) el.setAttribute("aria-label", val);
    });

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    try {
      localStorage.setItem("usk_lang", lang);
    } catch (e) {}

    window.USK_I18N.currentLang = lang;
    window.dispatchEvent(new CustomEvent("usklangchange", { detail: { lang: lang } }));
  }

  window.USK_I18N = {
    dict: DICT,
    statusLabels: STATUS_LABELS,
    originLabels: ORIGIN_LABELS,
    trackerInfo: STATUS_TRACKER_INFO,
    currentLang: "ru",
    apply: apply
  };

  document.addEventListener("DOMContentLoaded", function () {
    var urlLang = null;
    try {
      urlLang = new URLSearchParams(location.search).get("lang");
    } catch (e) {}

    var saved = null;
    try {
      saved = localStorage.getItem("usk_lang");
    } catch (e) {}

    var initial = (urlLang === "kk" || urlLang === "ru") ? urlLang : (saved === "kk" ? "kk" : "ru");
    apply(initial);

    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.addEventListener("click", function () {
        apply(btn.getAttribute("data-lang"));
      });
    });
  });
